from common import *
import io
m=load(); d0=pd.read_csv('results/p02/p02_county_dataset.csv',dtype={'fips':str})[['fips','oral_inc','oral_inc_avgcount','oral_mort','oral_late_rate','oral_inc_male','oral_inc_whiteNH','oral_inc_blackNH','lung_inc']]
d0=d0.merge(pd.read_csv('results/p02/p02_county_dataset.csv',dtype={'fips':str})[['fips']],on='fips')
m=m.merge(d0,on='fips',how='left')
# pct_late lives in the SCP long file
s=scp(); la=s[(s.dataset=='oral_late_all')&(~s.fips.isin(['28000','00000']))][['fips','pct_late']].rename(columns={'pct_late':'oral_pct_late'})
m=m.merge(la,on='fips',how='left')
out=io.StringIO()
def P(*a): print(*a,file=out)
P("# Paper 02 — public-data supplement (dental access, HPSA, PLACES 2020 dental visit)\n")
P("Generated by `p02b.py` 2026-11-27. New predictors: dentists in private practice per 10k (HRSA AHRF 2024-25, ADA masterfile 2023), dental HPSA designation (AHRF 2025 code; whole/part county), PLACES 2023-release dental visit and all-teeth-lost, age-adjusted (BRFSS 2020; the 2024/2025 PLACES dental visit values for Mississippi are implausible and excluded). Outcomes: SCP county all-race oral cavity & pharynx incidence 2019-23 (published for 54 counties) and % late stage (34 counties).\n")
m['dent_hpsa_whole']=(m.ahrf_hpsa_dent25==1).astype(float)
P("## A. Spearman correlations\n")
preds=[('dent_per10k','Dentists in private practice per 10k pop (AHRF 2023)'),('dentist_per100k','Dentists per 100k (CHR 2023)'),('pl20_dental','Dental visit past year, % (PLACES, BRFSS 2020)'),('pl20_teethlost','All teeth lost age>=65, % (PLACES, BRFSS 2020)'),('ahrf_hpsa_dent25','Dental HPSA code (0 none,1,2)'),('pl_csmoking','Current smoking % (PLACES BRFSS 2023)'),('nonmetro','Nonmetro'),('pct_black_nh','% Black NH'),('child_poverty','Child poverty %')]
rows=[]
for x,l in preds:
    n1,r1,p1=spearman(m[x],m.oral_inc); n2,r2,p2=spearman(m[x],m.oral_pct_late)
    rows.append([l,n1,r1,p1,n2,r2,p2])
P(pd.DataFrame(rows,columns=['Predictor','n (incidence)','rho','p','n (% late)','rho ','p ']).to_markdown(index=False,floatfmt='.3f')); P()
P("## B. Dental HPSA designation\n")
for y,l in [('oral_inc','incidence/100k'),('oral_pct_late','% late stage')]:
    g=m.groupby('ahrf_hpsa_dent25')[y].agg(['count','median']).round(1)
    P(f"{l}: "+'; '.join(f"code {int(k)}: n={int(v['count'])}, median {v['median']}" for k,v in g.iterrows())); 
P()
P("## C. OLS (HC3), oral cavity & pharynx incidence ~ access + risk\n")
xs=['dent_per10k','pl20_dental','pl_csmoking','nonmetro','child_poverty']
mod,t,n=ols(m,'oral_inc',xs); P(f"n={n}, R2={mod.rsquared:.2f}\n"); P(t.round(3).to_markdown()); P()
d=m[['oral_inc']+xs+['oral_inc_avgcount']].dropna(); X=sm.add_constant(d[xs]); w=sm.WLS(d.oral_inc,X,weights=d.oral_inc_avgcount).fit(cov_type='HC3')
P("WLS (weights = published average annual count)\n"); P(pd.DataFrame({'coef':w.params,'ci_lo':w.conf_int()[0],'ci_hi':w.conf_int()[1],'p':w.pvalues}).round(3).to_markdown()); P()
P("## D. OLS (HC3), % late stage ~ access (n small; exploratory)\n")
xs=['dent_per10k','pcp_per100k','nonmetro','pl_csmoking']
mod,t,n=ols(m,'oral_pct_late',xs); P(f"n={n}, R2={mod.rsquared:.2f}\n"); P(t.round(3).to_markdown()); P()
P("## E. Sensitivity: counties with vs without published oral incidence (suppression pattern)\n")
m['pub']=m.oral_inc.notna()
rows=[[l,m[m.pub][c].median(),m[~m.pub][c].median()] for c,l in [('population','Population'),('nonmetro','Share nonmetro'),('pct_black_nh','% Black NH'),('child_poverty','Child poverty %')]]
P(pd.DataFrame(rows,columns=['Variable','Median, published (n=54)','Median, suppressed (n=28)']).round(2).to_markdown(index=False)); P()
P("## F. Statewide oral-cavity/pharynx incidence vs lung incidence by county (smoking proxy)\n")
n,r,p=spearman(m.lung_inc,m.oral_inc); P(f"Spearman rho={r:.3f}, p={p:.3f}, n={n}\n")
m[['fips','county','nonmetro','dra_county','oral_inc','oral_pct_late','oral_mort','dent_per10k','ahrf_hpsa_dent25','pl20_dental','pl20_teethlost','pl_csmoking','pcp_per100k','population']].to_csv('results/p02/p02b_county_dataset.csv',index=False)
open('results/p02/p02b_results.md','w').write(out.getvalue()); print(out.getvalue())
